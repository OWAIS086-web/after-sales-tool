"""
DMS Metadata Vector Store Indexer

Indexes table metadata into ChromaDB for semantic schema retrieval.
Follows the same pattern as PakWheels/WhatsApp RAG pipeline.

Workflow:
1. Load all JSON metadata files from data/dms_metadata/
2. Extract searchable_text field for embedding
3. Index into ChromaDB: data/chroma_dms_haval/
4. Save metadata objects to PKL: data/dms_haval_metadata.pkl

Usage:
    python -m ai.dms_engine.metadata.index_metadata
"""

import json
import pickle
import os
from pathlib import Path
from typing import Dict, List, Optional
import chromadb

from ai.embeddings import SentenceTransformerEmbedder


class DMSTableMetadata:
    """
    Lightweight wrapper for table metadata.

    Matches the structure generated by generate_metadata.py.
    Used for storage in PKL and retrieval.
    """
    def __init__(self, metadata_dict: Dict):
        self.table_name = metadata_dict.get("table_name")
        self.business_name = metadata_dict.get("business_name", "")
        self.description = metadata_dict.get("description", "")
        self.business_domain = metadata_dict.get("business_domain", "")
        self.common_use_cases = metadata_dict.get("common_use_cases", [])
        self.columns = metadata_dict.get("columns", [])
        self.foreign_keys = metadata_dict.get("foreign_keys", [])
        self.indexes = metadata_dict.get("indexes", [])
        self.row_count = metadata_dict.get("row_count", 0)
        self.sample_queries = metadata_dict.get("sample_queries", [])
        self.searchable_text = metadata_dict.get("searchable_text", "")
        self.row_level_security_column = metadata_dict.get("row_level_security_column")
        self.metadata_version = metadata_dict.get("metadata_version", "1.0")

        # Store full dict for easy access
        self._raw = metadata_dict


class DMSMetadataVectorStore:
    """
    Vector store for DMS table metadata.

    Follows the same pattern as ChromaVectorStore in ai/vector_store.py.

    Design:
    - Embeds searchable_text field from each table metadata
    - Stores in ChromaDB for semantic search during LAYER 2 (Schema Retrieval)
    - Maintains full metadata in PKL file for LAYER 3 (Context Assembly)
    """

    def __init__(
        self,
        persist_path: str = "data/chroma_dms_haval",
        collection_name: str = "dms_haval_metadata",
        company: str = "haval",
        embedder: Optional[SentenceTransformerEmbedder] = None,
        metadata_pkl_file: Optional[str] = None,
    ):
        """
        Initialize DMS metadata vector store.

        Args:
            persist_path: ChromaDB persistence directory
            collection_name: Collection name in ChromaDB
            company: Company identifier (haval, kia, toyota)
            embedder: Embedding model (default: all-MiniLM-L6-v2)
            metadata_pkl_file: PKL file to save/load metadata objects
        """
        self.persist_path = persist_path
        self.collection_name = collection_name
        self.company = company

        # Initialize ChromaDB client
        os.makedirs(persist_path, exist_ok=True)
        self.client = chromadb.PersistentClient(path=persist_path)

        # Create/get collection
        self.collection = self.client.get_or_create_collection(
            name=collection_name,
            metadata={"hnsw:space": "cosine"}  # Cosine similarity for embeddings
        )

        # Initialize embedder (same as PakWheels/WhatsApp)
        self.embedder = embedder or SentenceTransformerEmbedder()

        # PKL file for full metadata storage
        self.metadata_pkl_file = metadata_pkl_file or f"data/dms_{company}_metadata.pkl"

        # In-memory metadata storage
        self._metadata_by_table: Dict[str, DMSTableMetadata] = self._load_metadata_pkl()

        print(f"\n[DMSMetadataVectorStore] Initialized")
        print(f"  Collection: {collection_name}")
        print(f"  ChromaDB: {persist_path}")
        print(f"  PKL File: {self.metadata_pkl_file}")
        print(f"  Loaded: {len(self._metadata_by_table)} tables from PKL")

    def _load_metadata_pkl(self) -> Dict[str, DMSTableMetadata]:
        """Load metadata from PKL file (if exists)."""
        if not os.path.exists(self.metadata_pkl_file):
            print(f"[DMSMetadataVectorStore] No existing PKL file, starting fresh")
            return {}

        try:
            with open(self.metadata_pkl_file, 'rb') as f:
                metadata_dict = pickle.load(f)
                print(f"[DMSMetadataVectorStore] Loaded {len(metadata_dict)} tables from {self.metadata_pkl_file}")
                return metadata_dict
        except Exception as e:
            print(f"[DMSMetadataVectorStore] Error loading PKL: {e}")
            return {}

    def _save_metadata_pkl(self) -> None:
        """Save metadata to PKL file."""
        try:
            os.makedirs(os.path.dirname(self.metadata_pkl_file), exist_ok=True)
            with open(self.metadata_pkl_file, 'wb') as f:
                pickle.dump(self._metadata_by_table, f)
            print(f"[DMSMetadataVectorStore] Saved {len(self._metadata_by_table)} tables to {self.metadata_pkl_file}")
        except Exception as e:
            print(f"[DMSMetadataVectorStore] Error saving PKL: {e}")

    def load_metadata_from_json_dir(self, metadata_dir: str) -> List[DMSTableMetadata]:
        """
        Load all metadata JSON files from directory.

        Args:
            metadata_dir: Directory containing JSON files (one per table)

        Returns:
            List of DMSTableMetadata objects
        """
        metadata_path = Path(metadata_dir)

        if not metadata_path.exists():
            raise FileNotFoundError(f"Metadata directory not found: {metadata_dir}")

        metadata_list = []
        json_files = list(metadata_path.glob("*.json"))

        print(f"\n[DMSMetadataVectorStore] Loading metadata from {metadata_dir}")
        print(f"  Found {len(json_files)} JSON files")

        for json_file in json_files:
            try:
                with open(json_file, 'r', encoding='utf-8') as f:
                    metadata_dict = json.load(f)
                    metadata_obj = DMSTableMetadata(metadata_dict)
                    metadata_list.append(metadata_obj)
            except Exception as e:
                print(f"  ⚠️  Error loading {json_file.name}: {e}")
                continue

        print(f"  ✅ Loaded {len(metadata_list)} table metadata objects")
        return metadata_list

    def index_metadata(self, metadata_list: List[DMSTableMetadata]) -> None:
        """
        Index table metadata into ChromaDB.

        Similar to ChromaVectorStore.index_blocks():
        - Uses table_name as ChromaDB ID
        - Embeds searchable_text field
        - Stores metadata for filtering
        - Avoids duplicates

        Args:
            metadata_list: List of table metadata objects to index
        """
        if not metadata_list:
            print("[DMSMetadataVectorStore] No metadata to index")
            return

        print(f"\n[DMSMetadataVectorStore] Indexing {len(metadata_list)} tables...")

        # Update in-memory storage
        for meta in metadata_list:
            self._metadata_by_table[meta.table_name] = meta

        # Get existing IDs from ChromaDB to avoid duplicates
        all_table_names = [meta.table_name for meta in metadata_list]

        try:
            existing = self.collection.get(ids=all_table_names, include=[])
            existing_ids = set(existing.get("ids", []))
        except Exception:
            existing_ids = set()

        # Filter out already indexed tables
        new_metadata = []
        for meta in metadata_list:
            if meta.table_name not in existing_ids:
                new_metadata.append(meta)

        if not new_metadata:
            print("  ℹ️  All tables already indexed, skipping")
            return

        print(f"  📊 New tables to index: {len(new_metadata)}")

        # Prepare data for ChromaDB
        ids = []
        documents = []
        metadatas = []
        embeddings = []

        for i, meta in enumerate(new_metadata, 1):
            # ID: table_name
            ids.append(meta.table_name)

            # Document: searchable_text (this gets embedded)
            documents.append(meta.searchable_text)

            # Metadata: for filtering and display
            metadatas.append({
                "table_name": meta.table_name,
                "business_name": meta.business_name,
                "business_domain": meta.business_domain,
                "row_count": meta.row_count,
                "has_rls": meta.row_level_security_column is not None,
            })

            # Generate embedding
            if i % 20 == 0:
                print(f"  Embedding: {i}/{len(new_metadata)}...")

            embedding = self.embedder.embed(meta.searchable_text)
            embeddings.append(embedding)

        # Add to ChromaDB
        print(f"  💾 Adding to ChromaDB...")
        self.collection.add(
            ids=ids,
            documents=documents,
            metadatas=metadatas,
            embeddings=embeddings
        )

        print(f"  ✅ Indexed {len(new_metadata)} tables into ChromaDB")

        # Save to PKL
        self._save_metadata_pkl()

    def get_metadata(self, table_name: str) -> Optional[DMSTableMetadata]:
        """
        Get full metadata for a table.

        Args:
            table_name: Table name

        Returns:
            DMSTableMetadata object or None
        """
        return self._metadata_by_table.get(table_name)

    def query_similar_tables(
        self,
        query: str,
        top_k: int = 10,
        domain_filter: Optional[str] = None
    ) -> List[Dict]:
        """
        Find tables semantically similar to query.

        This is LAYER 2 (Schema Retrieval) in the RAG pipeline.

        Args:
            query: Natural language query
            top_k: Number of tables to return
            domain_filter: Optional filter by business_domain

        Returns:
            List of dicts with table_name, relevance_score, metadata
        """
        # Embed query
        query_embedding = self.embedder.embed(query)

        # Build where filter
        where_filter = None
        if domain_filter:
            where_filter = {"business_domain": domain_filter}

        # Query ChromaDB
        results = self.collection.query(
            query_embeddings=[query_embedding],
            n_results=top_k,
            where=where_filter,
            include=["metadatas", "distances", "documents"]
        )

        # Format results
        similar_tables = []

        if results and results["ids"] and len(results["ids"]) > 0:
            ids_list = results["ids"][0]
            distances_list = results["distances"][0]
            metadatas_list = results["metadatas"][0]

            for i, table_name in enumerate(ids_list):
                # Convert distance to similarity score (0-1)
                distance = distances_list[i]
                similarity = 1.0 - distance  # Cosine distance → similarity

                similar_tables.append({
                    "table_name": table_name,
                    "relevance_score": similarity,
                    "business_name": metadatas_list[i].get("business_name", ""),
                    "business_domain": metadatas_list[i].get("business_domain", ""),
                    "row_count": metadatas_list[i].get("row_count", 0),
                })

        return similar_tables

    def get_stats(self) -> Dict:
        """Get statistics about indexed metadata."""
        return {
            "total_tables": len(self._metadata_by_table),
            "chromadb_count": self.collection.count(),
            "domains": self._get_domain_distribution(),
            "avg_row_count": self._get_avg_row_count(),
        }

    def _get_domain_distribution(self) -> Dict[str, int]:
        """Get count of tables by business domain."""
        domains = {}
        for meta in self._metadata_by_table.values():
            domain = meta.business_domain or "unknown"
            domains[domain] = domains.get(domain, 0) + 1
        return domains

    def _get_avg_row_count(self) -> int:
        """Get average row count across all tables."""
        if not self._metadata_by_table:
            return 0
        total = sum(meta.row_count for meta in self._metadata_by_table.values())
        return total // len(self._metadata_by_table)


def main():
    """
    Main indexing script.

    Loads metadata from data/dms_metadata/ and indexes into ChromaDB.
    """
    import argparse

    parser = argparse.ArgumentParser(description='Index DMS metadata into ChromaDB')
    parser.add_argument(
        '--metadata-dir',
        default='data/dms_metadata',
        help='Directory containing metadata JSON files'
    )
    parser.add_argument(
        '--company',
        default='haval',
        choices=['haval', 'kia', 'toyota'],
        help='Company identifier'
    )
    parser.add_argument(
        '--persist-path',
        default=None,
        help='ChromaDB persistence path (default: data/chroma_dms_{company})'
    )
    parser.add_argument(
        '--pkl-file',
        default=None,
        help='PKL file path (default: data/dms_{company}_metadata.pkl)'
    )

    args = parser.parse_args()

    # Set defaults based on company
    persist_path = args.persist_path or f"data/chroma_dms_{args.company}"
    pkl_file = args.pkl_file or f"data/dms_{args.company}_metadata.pkl"
    collection_name = f"dms_{args.company}_metadata"

    print(f"\n{'='*80}")
    print(f"DMS METADATA INDEXING PIPELINE")
    print(f"{'='*80}\n")
    print(f"Company: {args.company}")
    print(f"Metadata Directory: {args.metadata_dir}")
    print(f"ChromaDB Path: {persist_path}")
    print(f"Collection Name: {collection_name}")
    print(f"PKL File: {pkl_file}")
    print(f"\n{'='*80}\n")

    # Initialize vector store
    vector_store = DMSMetadataVectorStore(
        persist_path=persist_path,
        collection_name=collection_name,
        company=args.company,
        metadata_pkl_file=pkl_file,
    )

    # Load metadata from JSON files
    metadata_list = vector_store.load_metadata_from_json_dir(args.metadata_dir)

    if not metadata_list:
        print("\n❌ No metadata found to index!")
        return

    # Index into ChromaDB
    vector_store.index_metadata(metadata_list)

    # Print stats
    stats = vector_store.get_stats()
    print(f"\n{'='*80}")
    print(f"INDEXING COMPLETE")
    print(f"{'='*80}")
    print(f"Total Tables: {stats['total_tables']}")
    print(f"ChromaDB Count: {stats['chromadb_count']}")
    print(f"Average Row Count: {stats['avg_row_count']:,}")
    print(f"\nDomain Distribution:")
    for domain, count in sorted(stats['domains'].items()):
        print(f"  {domain:20} {count:3} tables")
    print(f"\n{'='*80}\n")

    # Test query
    print("🧪 Testing semantic search...")
    test_queries = [
        "repair orders and service history",
        "vehicle information and VIN",
        "customer data",
        "invoices and payments"
    ]

    for query in test_queries:
        print(f"\nQuery: '{query}'")
        results = vector_store.query_similar_tables(query, top_k=3)
        for i, result in enumerate(results, 1):
            print(f"  {i}. {result['table_name']:20} "
                  f"({result['business_name']:30}) "
                  f"Score: {result['relevance_score']:.3f}")

    print(f"\n✅ All done!\n")


if __name__ == '__main__':
    main()
